CREATE TABLE IF NOT EXISTS items(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 kind TEXT NOT NULL, date TEXT, grade TEXT, section TEXT, subject TEXT,
 title TEXT, text TEXT, coverage TEXT, link TEXT, type TEXT, author TEXT,
 created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_kind_date ON items(kind,date);
CREATE TABLE IF NOT EXISTS subs(
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 endpoint TEXT NOT NULL UNIQUE, grade TEXT DEFAULT '',
 created_at TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS logins(
 ip TEXT NOT NULL, ts TEXT DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_logins ON logins(ip,ts);
